// the four BSP functions. Nothing else of MicroQuick depends on the hardware.
//
// Typical targets: STM32F7/H7 (LTDC + SDRAM framebuffer), NXP i.MX RT,
// RP2040/ESP32 with an SPI display (use the dirty rectangles to push only
// changed pixels).

#include <mq/mq.h>

mq::Item *mq_app_root();   // generated by mqc

// ---------------------------------------------------------------- BSP hooks
// Framebuffer in RGB565. 480x272x2 = 255 KiB: place it in SDRAM/PSRAM
// (e.g. with __attribute__((section(".sdram")))) on small MCUs.
static uint16_t framebuffer[480 * 272];

extern "C" uint32_t bsp_millis();                                  // SysTick / RTOS tick
extern "C" bool bsp_touch_read(int *x, int *y);                    // true while touched
extern "C" void bsp_display_flush(const uint16_t *fb, int stride,  // copy / DMA a rectangle
                                  int x, int y, int w, int h);
extern "C" void bsp_wait_vsync();                                  // or a ~16 ms delay

// Optional: route console.log and fatal errors to a UART.
// namespace mq { void log(const char *msg) { uart_puts(msg); } }

int main()
{
    mq::Window *window = mq::Window::instance();
    window->setFramebuffer(framebuffer, 480, 272);
    window->setRoot(mq_app_root());

    bool wasDown = false;
    for (;;) {
        int x = 0, y = 0;
        bool down = bsp_touch_read(&x, &y);
        if (down && !wasDown) window->pointerEvent(mq::PointerAction::Press, x, y);
        else if (down) window->pointerEvent(mq::PointerAction::Move, x, y);
        else if (wasDown) window->pointerEvent(mq::PointerAction::Release, x, y);
        wasDown = down;

        mq::Rect dirty[MQ_MAX_DIRTY_RECTS];
        int n = window->processFrame(bsp_millis(), dirty);
        for (int i = 0; i < n; ++i)
            bsp_display_flush(framebuffer, 480, dirty[i].x, dirty[i].y, dirty[i].w, dirty[i].h);
        bsp_wait_vsync();
    }
}
