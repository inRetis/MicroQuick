// MicroQuick port for the M5Stack Core2.
//
// Hardware: ESP32 (240 MHz, 8 MB PSRAM), ILI9342C 320x240 display on SPI,
// FT6336U capacitive touch, AXP192 power management. M5Unified powers the
// display (AXP192), drives it (M5GFX) and reads the touch panel.
//
// The MicroQuick runtime itself never allocates. This port makes three
// allocations, once at startup: the framebuffer in PSRAM (150 KB), and the
// application state + binding link pool in internal RAM (see
// mq_platform_alloc below).

#include <M5Unified.h>
#include <esp_heap_caps.h>
#include <mq/mq.h>

mq::Item *mq_app_root();   // generated by mqc (src/mq_generated)

namespace {

uint16_t *framebuffer = nullptr;
int screenW = 0, screenH = 0;
bool touching = false;
uint32_t lastStats = 0;

// Sends the repainted rectangles to the display. The framebuffer holds native
// RGB565 pixels; lgfx::rgb565_t tells M5GFX so (it swaps the bytes for SPI).
void flush(const mq::Rect *rects, int count)
{
    M5.Display.startWrite();
    for (int i = 0; i < count; ++i) {
        const mq::Rect &r = rects[i];
        M5.Display.setAddrWindow(r.x, r.y, r.w, r.h);
        for (int y = r.y; y < r.bottom(); ++y)
            M5.Display.writePixels(reinterpret_cast<const lgfx::rgb565_t *>(framebuffer + y * screenW + r.x), r.w);
    }
    M5.Display.endWrite();
}

void readTouch(mq::Window *window)
{
    // Core2: the touch panel extends below the screen (y 240..279) where the
    // three red circles are: presses there are ignored.
    const auto &t = M5.Touch.getDetail();
    const bool down = M5.Touch.getCount() > 0 && t.isPressed();
    const int x = mq::clamp(int(t.x), 0, screenW - 1);
    const int y = mq::clamp(int(t.y), 0, screenH - 1);
    if (down && !touching) {
        if (t.y >= screenH) return;
        touching = true;
        window->pointerEvent(mq::PointerAction::Press, x, y);
    } else if (down && touching) {
        window->pointerEvent(mq::PointerAction::Move, x, y);
    } else if (!down && touching) {
        touching = false;
        window->pointerEvent(mq::PointerAction::Release, x, y);
    }
}

} // namespace

// Memory for the application state and the binding link pool, requested once
// by mq_app_root() (MQ_APP_PLATFORM_STORAGE): internal RAM, the fastest.
void *mq_platform_alloc(size_t size, size_t align)
{
    void *p = heap_caps_aligned_alloc(align < 4 ? 4 : align, size, MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT);
    if (!p) p = heap_caps_aligned_alloc(align < 4 ? 4 : align, size, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!p) {
        Serial.printf("MicroQuick: cannot allocate %u bytes\n", unsigned(size));
        abort();
    }
    return p;
}

// console.log() -> serial monitor
namespace mq {
void log(const char *message)
{
    Serial.print("qml: ");
    Serial.println(message);
}
} // namespace mq

void setup()
{
    auto cfg = M5.config();
    cfg.serial_baudrate = 115200;
    M5.begin(cfg);
    // M5Unified already sets the Core2 display in landscape (320x240); make sure
    // of it in case the UI is landscape and the panel was left in portrait.
    if (M5.Display.width() < M5.Display.height())
        M5.Display.setRotation((M5.Display.getRotation() + 1) & 3);
    M5.Display.setBrightness(160);
    screenW = M5.Display.width();
    screenH = M5.Display.height();

    framebuffer = static_cast<uint16_t *>(
        heap_caps_malloc(size_t(screenW) * screenH * 2, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
    if (!framebuffer) {
        Serial.println("MicroQuick: no PSRAM framebuffer, falling back to internal RAM");
        framebuffer = static_cast<uint16_t *>(malloc(size_t(screenW) * screenH * 2));
    }
    if (!framebuffer) {
        M5.Display.drawString("MicroQuick: framebuffer allocation failed", 4, 4);
        for (;;) delay(1000);
    }

    mq::Window *window = mq::Window::instance();
    window->setFramebuffer(framebuffer, screenW, screenH);
    window->setRoot(mq_app_root());
    Serial.printf("MicroQuick: %dx%d, free internal heap %u bytes\n", screenW, screenH,
                  unsigned(heap_caps_get_free_size(MALLOC_CAP_INTERNAL)));
}

void loop()
{
    M5.update();
    mq::Window *window = mq::Window::instance();
    readTouch(window);

    mq::Rect dirty[MQ_MAX_DIRTY_RECTS];
    const int n = window->processFrame(millis(), dirty);
    if (n > 0) flush(dirty, n);

    // every 10 s: rendering and memory statistics on the serial monitor
    if (millis() - lastStats > 10000) {
        lastStats = millis();
        const mq::LinkPoolStats links = mq::linkPoolStats();
        Serial.printf("MicroQuick: %u frames, links %d/%d (peak %d), free heap %u\n",
                      unsigned(window->framesRendered()), links.used, links.size, links.peak,
                      unsigned(heap_caps_get_free_size(MALLOC_CAP_INTERNAL)));
    }
    delay(5);   // ~200 Hz input polling, leaves time to the idle task
}
